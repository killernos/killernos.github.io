import assert from 'node:assert/strict';
import {validateCorrelationReport,deriveReviewQueue,updateReviewState,attachSourceReference,summarizeReviewQueue} from '../runtime/next-1302/candidate-review-queue.js';
const base={reportType:'NEXT_HARDWARE_SOURCE_CORRELATION',evidenceClass:'HARDWARE_OBSERVED',firmwareSource:'UA',firmware:'13.02',automaticExploitPromotion:false,kernelExecutionAuthorized:false,kernelWriteAuthorized:false,henAuthorized:false,matchedDifferences:[{key:'candidate_symbol',baseFirmware:'13.00',targetFirmware:'13.02',state:'CHANGED'}]};
assert.equal(validateCorrelationReport(base).ok,true);
assert.equal(validateCorrelationReport({...base,kernelExecutionAuthorized:true}).ok,false);
let queue=deriveReviewQueue([base]);
assert.equal(queue[0].reviewState,'HARDWARE_OBSERVED');
assert.equal(queue[0].candidateEligible,false);
queue=deriveReviewQueue([base,{...base}]);
assert.equal(queue[0].reviewState,'REPRODUCED');
assert.equal(queue[0].candidateEligible,true);
assert.equal(queue[0].exploitProven,false);
const candidate=updateReviewState(queue[0],'CANDIDATE','independent reproduction reviewed');
assert.equal(candidate.reviewState,'CANDIDATE');
assert.equal(candidate.exploitProven,false);
assert.throws(()=>updateReviewState({...queue[0],candidateEligible:false,reproductions:1},'CANDIDATE'));
const sourced=attachSourceReference(candidate,{url:'https://example.invalid/research','label':'source lead',evidenceClass:'SOURCE_CONFIRMED'});
assert.equal(sourced.sources.length,1);
assert.throws(()=>attachSourceReference(candidate,{url:'https://example.invalid/forged','evidenceClass':'HARDWARE_OBSERVED'}));
const summary=summarizeReviewQueue([candidate]);
assert.equal(summary.total,1); assert.equal(summary.CANDIDATE,1);
console.log('candidate review queue regression tests passed');
